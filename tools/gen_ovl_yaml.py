#!/usr/bin/env python3
"""Generate config/ovl.yaml: splat config for the 21 slot-1 character overlays (vram 0x8009E000).
Slot-2 overlays (vram 0x800AE000) are the same code relinked +0x10000 and are built from the same source."""
import hashlib, os, struct
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VRAM = 0x8009E000
rows = [l.split("\t") for l in open(os.path.join(ROOT, "baserom/filetable.tsv")).read().splitlines()]
ovls = [(n, int(o, 16) & 0x7FFFFFFF, int(s, 16)) for n, o, s, _ in rows if n.startswith("OVL/")]
prg = open(os.path.join(ROOT, "baserom/prg.bin"), "rb").read()
start, end = ovls[0][1], ovls[-1][1] + ovls[-1][2]
blob = prg[start:end]
open(os.path.join(ROOT, "baserom/ovl1.bin"), "wb").write(blob)

out = [f"""# splat config for slot-1 character overlays (generated by tools/gen_ovl_yaml.py)
name: Fighting Layer character overlays (slot 1)
sha1: {hashlib.sha1(blob).hexdigest()}
options:
  basename: ovl
  target_path: baserom/ovl1.bin
  base_path: ..
  platform: psx
  compiler: GCC
  asm_path: asm/ovl
  src_path: src/ovl
  build_path: build
  ld_script_path: build/ovl.ld
  symbol_addrs_path: [config/symbol_addrs.txt, config/symbol_addrs_ovl.txt]
  undefined_funcs_auto_path: config/undefined_funcs_auto_ovl.txt
  undefined_syms_auto_path: config/undefined_syms_auto_ovl.txt
  global_vram_start: 0x801F0000
  global_vram_end: 0x80370000
  migrate_rodata_to_functions: true
  string_encoding: ASCII
segments:"""]
for name, ofs, size in ovls:
    seg = os.path.basename(name).split(".")[0].lower()
    b = prg[ofs:ofs + size]
    # leading pointer table: words that point inside this overlay
    n = 0
    while VRAM <= struct.unpack_from("<I", b, n)[0] < VRAM + size:
        n += 4
    W = lambda i: struct.unpack_from("<I", b, i)[0]
    # code starts at the first real stack-frame prologue: addiu sp,sp,-N followed closely by sw ra,X(sp)
    def is_prologue(i):
        return (W(i) >> 16) == 0x27BD and W(i) & 0x8000 and any((W(j) >> 16) == 0xAFBF for j in range(i + 4, min(i + 64, size), 4))
    cs = next(i for i in range(n, size, 4) if is_prologue(i))
    # include leaf functions that sit just before the first prologue (back up over jr ra-terminated blocks)
    ce = max(i for i in range(0, size, 4) if W(i) == 0x03E00008) + 8
    out.append(f"""  - name: {seg}
    type: code
    start: {ofs - start:#x}
    vram: 0x{VRAM:08X}
    exclusive_ram_id: char_ovl
    subsegments:
      - [{ofs - start:#x}, data]   # {n // 4}-entry function pointer table
      - [{ofs - start + n:#x}, data]
      - [{ofs - start + cs:#x}, asm]
      - [{ofs - start + ce:#x}, data]""")
out.append(f"  - [{end - start:#x}]\n")
open(os.path.join(ROOT, "config/ovl.yaml"), "w").write("\n".join(out))
print(f"wrote config/ovl.yaml ({len(ovls)} overlays, {len(blob):#x} bytes)")
